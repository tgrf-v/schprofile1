-- ==============================================================================
-- STORAGE BUCKET UNTUK UPLOAD GAMBAR ('school-media')
-- ==============================================================================
INSERT INTO storage.buckets (id, name, public)
VALUES ('school-media', 'school-media', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Policy Storage: Publik dapat membaca / melihat gambar
DROP POLICY IF EXISTS "Media dapat dilihat publik" ON storage.objects;
CREATE POLICY "Media dapat dilihat publik" ON storage.objects
    FOR SELECT USING (bucket_id = 'school-media');

-- Policy Storage: Admin terautentikasi dapat mengunggah gambar
DROP POLICY IF EXISTS "Admin dapat mengunggah media" ON storage.objects;
CREATE POLICY "Admin dapat mengunggah media" ON storage.objects
    FOR INSERT TO authenticated WITH CHECK (bucket_id = 'school-media');

DROP POLICY IF EXISTS "Admin dapat menghapus media" ON storage.objects;
CREATE POLICY "Admin dapat menghapus media" ON storage.objects
    FOR DELETE TO authenticated USING (bucket_id = 'school-media');

