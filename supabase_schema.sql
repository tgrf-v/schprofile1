-- 1. TABEL BERITA & ARTIKEL (articles)
CREATE TABLE IF NOT EXISTS public.articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT DEFAULT 'Berita',
    date TEXT,
    author TEXT DEFAULT 'Admin Sekolah',
    image TEXT,
    excerpt TEXT,
    content TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABEL PENGUMUMAN (announcements)
CREATE TABLE IF NOT EXISTS public.announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    date TEXT,
    image TEXT,
    content TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABEL GALERI KEGIATAN (gallery)
CREATE TABLE IF NOT EXISTS public.gallery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT DEFAULT 'Kegiatan',
    date TEXT,
    description TEXT,
    image_url TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- PENGATURAN KEAMANAN & AKSES (Row Level Security / RLS)
-- Aturan: Publik (siapapun) bisa membaca data, tapi HANYA user terdaftar
-- (Admin yang login) yang bisa Menambah, Mengedit, dan Menghapus data.
-- ==============================================================================

ALTER TABLE public.articles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.announcements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.gallery ENABLE ROW LEVEL SECURITY;

-- Policy untuk Articles
DROP POLICY IF EXISTS "Publik dapat membaca artikel" ON public.articles;
CREATE POLICY "Publik dapat membaca artikel" ON public.articles
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Admin dapat menambah artikel" ON public.articles;
CREATE POLICY "Admin dapat menambah artikel" ON public.articles
    FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Admin dapat mengedit artikel" ON public.articles;
CREATE POLICY "Admin dapat mengedit artikel" ON public.articles
    FOR UPDATE TO authenticated USING (true);

DROP POLICY IF EXISTS "Admin dapat menghapus artikel" ON public.articles;
CREATE POLICY "Admin dapat menghapus artikel" ON public.articles
    FOR DELETE TO authenticated USING (true);

